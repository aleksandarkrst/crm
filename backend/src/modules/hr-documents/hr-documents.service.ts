import { ConflictException, Inject, Injectable, Logger, Optional } from '@nestjs/common';
import { and, desc, eq, inArray, sql } from 'drizzle-orm';
import { createHash } from 'node:crypto';
import { ENV, type Env } from '../../infrastructure/config/config.module';
import { type MailAttachment, Mailer } from '../../infrastructure/mail/mailer';
import { StorageService } from '../../infrastructure/storage/storage.service';
import { DatabaseService, type Tx } from '../../shared/database/database.service';
import { employees, type HrDocumentRow, type HrDocumentState, type HrDocumentType, hrDocuments, memberships, tenants, users } from '../../shared/database/schema';
import type { JobAttempt } from '../../shared/events/jobs.service';
import { JobsService } from '../../shared/events/jobs.service';
import { type PdfDocumentSpec, renderPdf, TEMPLATE_VERSION } from './pdf';

/** Thrown by a renderer when the snapshot can't make a document (missing company details): a readable reason, no retry. */
export class DocumentDataError extends Error {}

/**
 * How each document type turns its snapshot into a document, and what its emails say. The owning
 * module registers its type on start (the timeoff module for `vacation_decision`), so this module
 * imports none of them. The registering service must be provided in the worker too
 * (TimeoffWorkerModule provides DecisionsService), or that type's documents fail to generate.
 */
export interface DocumentRenderer<S = unknown> {
  render(snapshot: S, doc: HrDocumentRow): PdfDocumentSpec;
  /** The file name the employee downloads and the email attachment carries. */
  fileName(doc: HrDocumentRow, snapshot: S): string;
  /** The "ready" email's subject and the line before the attachment note. */
  email(doc: HrDocumentRow, snapshot: S): { subject: string; intro: string };
  /** What the document is called in the failure email ("vacation decision"). */
  label: string;
}

export const documentRenderers = new Map<HrDocumentType, DocumentRenderer>();

export const NUMBER_PREFIX: Record<HrDocumentType, string> = { vacation_decision: 'GO' };

export interface QueueInput {
  tenantId: string;
  type: HrDocumentType;
  sourceId: string;
  employeeId: string;
  /** The year the number's sequence belongs to (the year of the leave, spec 10.1). */
  year: number;
  snapshot: unknown;
  createdByUserId: string | null;
}

/**
 * The shared engine for generated legal documents (spec 10.2, 10.3): numbers them from a yearly
 * sequence per type, generates the PDF in the worker (`documents.generate-pdf`), stores it as
 * `hr-documents/<id>-v<version>.pdf` under the tenant, and emails it (`documents.email`) to the
 * employee and the workspace's decision recipients (spec 12), or the Admins when it failed.
 * Callers check permissions and find rows with `withTenant`; this service never does.
 */
@Injectable()
export class HrDocumentsService {
  private readonly logger = new Logger(HrDocumentsService.name);

  constructor(
    private readonly database: DatabaseService,
    private readonly storage: StorageService,
    private readonly jobs: JobsService,
    @Inject(ENV) private readonly env: Env,
    // Only the worker sends email (the API has no mail driver): `email` runs there.
    @Optional() private readonly mailer?: Mailer,
  ) {}

  /** A new document with the next number of its type and year; generated by the worker once `tx` commits. */
  async queue(tx: Tx, input: QueueInput): Promise<HrDocumentRow> {
    // Two approvals at once get two numbers (spec 11.6.2): the sequence is read under a lock per workspace and type.
    await tx.execute(sql`select pg_advisory_xact_lock(hashtext(${`${input.tenantId}:hr_documents:${input.type}`}))`);
    const [last] = await tx
      .select({ n: sql<number>`coalesce(max(${hrDocuments.sequence}), 0)::int` })
      .from(hrDocuments)
      .where(and(eq(hrDocuments.type, input.type), eq(hrDocuments.year, input.year)));
    const sequence = (last?.n ?? 0) + 1;
    const number = `${NUMBER_PREFIX[input.type]}-${input.year}-${String(sequence).padStart(4, '0')}`;
    const [row] = await tx
      .insert(hrDocuments)
      .values({ tenantId: input.tenantId, type: input.type, sourceId: input.sourceId, employeeId: input.employeeId, number, year: input.year, sequence, snapshot: input.snapshot, templateVersion: TEMPLATE_VERSION, createdByUserId: input.createdByUserId })
      .returning();
    await this.jobs.send('documents.generate-pdf', { tenantId: input.tenantId, documentId: row!.id }, tx);
    return row!;
  }

  /** A new version of `current` with the same number (spec 11.5); the earlier one becomes superseded and stays downloadable. */
  async newVersion(tx: Tx, current: HrDocumentRow, snapshot: unknown, createdByUserId: string | null, email: boolean): Promise<HrDocumentRow> {
    // Two Admins regenerating at once: the second waits here and then finds the row superseded.
    const [locked] = await tx.select({ state: hrDocuments.state }).from(hrDocuments).where(eq(hrDocuments.id, current.id)).for('update');
    if (locked?.state === 'superseded' || locked?.state === 'cancelled') throw new ConflictException('A newer version exists, or the decision was cancelled');
    await tx.update(hrDocuments).set({ state: 'superseded' }).where(eq(hrDocuments.id, current.id));
    const [row] = await tx
      .insert(hrDocuments)
      .values({ tenantId: current.tenantId, type: current.type, sourceId: current.sourceId, employeeId: current.employeeId, number: current.number, year: current.year, sequence: current.sequence, version: current.version + 1, snapshot, templateVersion: TEMPLATE_VERSION, createdByUserId, emailOnReady: email })
      .returning();
    await this.jobs.send('documents.generate-pdf', { tenantId: current.tenantId, documentId: row!.id }, tx);
    return row!;
  }

  /** The current (not superseded) version of a source's document, if any. */
  async currentFor(tx: Tx, type: HrDocumentType, sourceIds: string[]): Promise<Map<string, HrDocumentRow>> {
    if (!sourceIds.length) return new Map();
    const rows = await tx
      .select()
      .from(hrDocuments)
      .where(and(eq(hrDocuments.type, type), inArray(hrDocuments.sourceId, sourceIds)))
      .orderBy(desc(hrDocuments.version));
    const out = new Map<string, HrDocumentRow>();
    for (const r of rows) if (!out.has(r.sourceId)) out.set(r.sourceId, r);
    return out;
  }

  /** The source changed (shortened: outdated; cancelled): every version of its document says so. The PDF stays. */
  async setState(tx: Tx, type: HrDocumentType, sourceId: string, state: Exclude<HrDocumentState, 'superseded'>): Promise<void> {
    await tx
      .update(hrDocuments)
      .set({ state })
      .where(and(eq(hrDocuments.type, type), eq(hrDocuments.sourceId, sourceId), inArray(hrDocuments.state, ['valid', 'outdated'])));
  }

  async acknowledge(tx: Tx, id: string): Promise<HrDocumentRow | null> {
    const [row] = await tx
      .update(hrDocuments)
      .set({ acknowledgedAt: new Date() })
      .where(and(eq(hrDocuments.id, id), sql`${hrDocuments.acknowledgedAt} is null`))
      .returning();
    return row ?? null;
  }

  /** The PDF of a ready document, and its file name. */
  async file(doc: HrDocumentRow): Promise<{ name: string; content: Buffer } | null> {
    if (doc.status !== 'ready' || !doc.storageKey) return null;
    const renderer = documentRenderers.get(doc.type);
    if (!renderer) return null;
    return { name: renderer.fileName(doc, doc.snapshot), content: await this.storage.getBuffer(doc.tenantId, doc.storageKey) };
  }

  /**
   * `documents.generate-pdf` in the worker: renders and stores the PDF, marks the row ready, then
   * queues the email. A retry (`attempt.retryCount` > 0) takes over a document left running by a
   * stopped worker (CD-100). A data problem fails the document with its reason and tells the
   * Admins; nothing retries it (the data is the same every time) until someone regenerates.
   */
  async generate(tenantId: string, documentId: string, attempt: Pick<JobAttempt, 'retryCount'> = { retryCount: 0 }): Promise<void> {
    const claimable = attempt.retryCount > 0 ? inArray(hrDocuments.status, ['queued', 'running']) : eq(hrDocuments.status, 'queued');
    const doc = await this.database.withTenant(tenantId, async (tx) => {
      const [row] = await tx.update(hrDocuments).set({ status: 'running', error: null, updatedAt: new Date() }).where(and(eq(hrDocuments.id, documentId), claimable)).returning();
      return row ?? null;
    });
    if (!doc) return;
    try {
      const renderer = documentRenderers.get(doc.type);
      if (!renderer) throw new Error(`No renderer for ${doc.type}`);
      const pdf = await renderPdf(renderer.render(doc.snapshot, doc));
      const key = `hr-documents/${doc.id}-v${doc.version}.pdf`;
      await this.storage.putBuffer(tenantId, key, pdf);
      await this.database.withTenant(tenantId, async (tx) => {
        await tx.update(hrDocuments).set({ status: 'ready', storageKey: key, sizeBytes: pdf.length, sha256: createHash('sha256').update(pdf).digest('hex') }).where(eq(hrDocuments.id, doc.id));
        if (doc.emailOnReady) await this.jobs.send('documents.email', { tenantId, documentId: doc.id, kind: 'ready' }, tx);
      });
    } catch (err) {
      const message = err instanceof DocumentDataError ? err.message : 'Something went wrong while generating the document. Generate it again.';
      if (!(err instanceof DocumentDataError)) this.logger.error(err, `Generating document ${doc.id} failed`);
      await this.database.withTenant(tenantId, async (tx) => {
        await tx.update(hrDocuments).set({ status: 'failed', error: message }).where(eq(hrDocuments.id, doc.id));
        await this.jobs.send('documents.email', { tenantId, documentId: doc.id, kind: 'failed' }, tx);
      });
    }
  }

  /**
   * `documents.email` in the worker. `ready`: the PDF to the employee (their sign-in email, else
   * the work email) and the decision recipients, resolved now (spec 12.2), one message each, the
   * addresses kept on the row. `failed`: "could not be generated" to the Admins.
   */
  async email(data: { tenantId: string; documentId: string; kind: 'ready' | 'failed' }): Promise<void> {
    const facts = await this.database.withTenant(data.tenantId, async (tx) => {
      const [doc] = await tx.select().from(hrDocuments).where(eq(hrDocuments.id, data.documentId));
      if (!doc) return null;
      const [t] = await tx.select({ name: tenants.name, copyAdmins: tenants.decisionCopyAdmins, copyEmails: tenants.decisionCopyEmails }).from(tenants).where(eq(tenants.id, data.tenantId));
      const [e] = await tx.select({ fullName: employees.fullName, userId: employees.userId, workEmail: employees.workEmail }).from(employees).where(eq(employees.id, doc.employeeId));
      const employeeEmail = (e?.userId ? (await tx.select({ email: users.email }).from(users).where(eq(users.id, e.userId)))[0]?.email : null) ?? e?.workEmail ?? null;
      const admins = data.kind === 'failed' || t?.copyAdmins ? await this.adminAddresses(tx, data.tenantId) : [];
      return { doc, workspaceName: t?.name ?? 'Pultly', copyEmails: t?.copyEmails ?? [], employeeName: e?.fullName ?? 'the employee', employeeEmail, admins };
    });
    if (!facts) return;
    if (!this.mailer) throw new Error('documents.email runs in the worker');
    const mailer = this.mailer;
    const { doc } = facts;
    const renderer = documentRenderers.get(doc.type);
    if (!renderer) return;
    const link = `${this.env.APP_URL}/timeoff`;
    if (data.kind === 'failed') {
      const subject = `${capitalize(renderer.label)} could not be generated: ${facts.employeeName}`;
      const text = `The ${renderer.label} ${doc.number} for ${facts.employeeName} in ${facts.workspaceName} could not be generated.\n\nReason: ${doc.error ?? 'unknown'}\n\nFix the cause in Settings and generate it again on the Decisions tab: ${link}?tab=decisions`;
      for (const to of facts.admins) await mailer.send({ to, subject, text, html: html(text) });
      return;
    }
    // Regenerated meanwhile (that version sends its own) or cancelled: nothing to send.
    if (doc.status !== 'ready' || doc.state === 'superseded' || doc.state === 'cancelled') return;
    const file = await this.file(doc);
    if (!file) return;
    const attachment: MailAttachment = { filename: file.name, contentType: 'application/pdf', content: file.content.toString('base64'), encoding: 'base64' };
    const { subject, intro } = renderer.email(doc, doc.snapshot);
    // A retry after a partial send skips the addresses that already got it.
    const done = doc.emailedTo ?? [];
    const recipients = [...new Set([facts.employeeEmail, ...facts.admins, ...facts.copyEmails].filter((a): a is string => !!a && !done.includes(a)))];
    const sent: string[] = [...done];
    for (const to of recipients) {
      const forEmployee = to === facts.employeeEmail;
      const text = `${intro}\n\nThe document is attached as a PDF (${file.name}).${forEmployee ? `\n\nPlease confirm receipt on your request in Pultly: ${link}` : ` Sent to ${facts.employeeName}${facts.employeeEmail ? '' : ' (no email address: hand it over in person)'} and, as a copy, to you.`}\n\nWorkspace: ${facts.workspaceName}`;
      try {
        const result = await mailer.send({ to, subject, text, html: html(text), attachments: [attachment] });
        if (!result.rejected.includes(to)) sent.push(to);
      } catch (err) {
        this.logger.warn(`Document ${doc.id}: email to ${to} failed: ${err instanceof Error ? err.message : String(err)}`);
      }
    }
    await this.database.withTenant(data.tenantId, (tx) => tx.update(hrDocuments).set({ emailedTo: sent, emailedAt: sent.length ? new Date() : null }).where(eq(hrDocuments.id, doc.id)));
    const missed = recipients.filter((a) => !sent.includes(a)).length;
    if (missed) throw new Error(`Document ${doc.id}: ${missed} of ${recipients.length} email(s) not sent`);
  }

  /** The backstop (spec 10.3): documents running for over an hour in this workspace fail with a reason; Admins regenerate. */
  async failInterrupted(tenantId: string): Promise<number> {
    const rows = await this.database.withTenant(tenantId, (tx) =>
      tx
        .update(hrDocuments)
        .set({ status: 'failed', error: 'Generation was interrupted. Generate it again.' })
        .where(and(eq(hrDocuments.status, 'running'), sql`${hrDocuments.updatedAt} < now() - interval '1 hour'`))
        .returning({ id: hrDocuments.id }),
    );
    return rows.length;
  }

  private async adminAddresses(tx: Tx, tenantId: string): Promise<string[]> {
    const rows = await tx
      .select({ email: users.email })
      .from(memberships)
      .innerJoin(users, eq(users.id, memberships.userId))
      .where(and(eq(memberships.tenantId, tenantId), inArray(memberships.role, ['owner', 'admin'])));
    return rows.map((r) => r.email).filter((e): e is string => !!e);
  }
}

const capitalize = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
const html = (text: string) => `<p>${text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/\n\n/g, '</p><p>').replace(/\n/g, '<br>')}</p>`;
