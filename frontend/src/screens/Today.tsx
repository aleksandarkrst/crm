import { useMemo } from 'react';
import { Link } from 'react-router-dom';
import { FilterBar } from '../components/ui';
import { EmptyState } from '../components/EmptyState';
import { FilterEmpty, FilterRow } from '../components/FilterRow';
import { Screen } from '../components/Layout';
import { filterPeople, type FilterTask, taskFields } from '../store/filterFields';
import { applyFilters, clearAll } from '../store/filters';
import { CHANNEL_LABELS } from '../store/seed';
import { isoLabel, isOverdue, leadById, memberName, stageOf, stagesFor, todayIso, todayLabel } from '../store/selectors';
import { useStore } from '../store/store';
import { usePageFilters } from '../store/usePageFilters';
import { paths } from '../lib/paths';
import { addDays, dayRange, instantToZoned, todayIn } from '../store/time';
import { useMeetingList } from '../store/useMeetings';
import { TeamTodayCard } from './teamStatus/parts';
import { blockClass, StatusMark, TypeTag } from './calendar/parts';

interface TodayTask extends FilterTask {
  id: string;
  leadId: string;
  company: string;
  due: string;
  bucket: number;
  /** Set for tasks added with "New task" (they can be ticked off and edited here). */
  task?: { done: boolean; owner: string; dueIso: string; overdue: boolean };
}

/**
 * "Today": tasks generated by the funnel (each lead's current stage activity) plus tasks added by
 * hand. Overdue (CD-67) holds the hand-added tasks that are past their due date and not done, by
 * the workspace's today (its time zone); the funnel's tasks have no due date, so they are never
 * overdue: a deal that has been quiet for a while sits under Today.
 */
export function Today() {
  const { s, set, openLead, toggleLeadTask, session } = useStore();
  const me = session.userId;
  const [filters, setFilters] = usePageFilters('today', { order: ['owner'], f: { owner: { op: 'is', vals: [me] } } });
  const owners = filters.f.owner?.vals ?? [];
  // Meetings today (CD-130): yours as organizer or internal participant, or the one chosen salesperson's.
  // Several people ticked: the day's meetings, kept when any of them organizes or takes part.
  const tz = s.workspace.timezone;
  const day = todayIn(tz);
  const range = useMemo(() => dayRange(day, tz), [day, tz]);
  const many = owners.length > 1;
  const { meetings: dayMeetings } = useMeetingList({ from: new Date(range.from).toISOString(), to: new Date(range.to).toISOString(), userId: many ? undefined : owners.length === 1 ? owners[0] : session.userId, status: ['planned', 'held'], sort: 'asc' });
  const todays = many ? dayMeetings.filter((m) => owners.includes(m.organizerUserId ?? '') || m.participants.some((p) => p.kind === 'internal' && !!p.userId && owners.includes(p.userId))) : dayMeetings;

  const today = todayIso(s.workspace.timezone);
  const doneToday = todayLabel(s.workspace.timezone);
  const funnelTasks = s.leads
    .map<TodayTask>((l) => {
      const st = stageOf(s, l);
      return {
        id: l.id,
        leadId: l.id,
        title: st.activity,
        company: l.company,
        stageName: st.name,
        channelLabel: CHANNEL_LABELS[st.channel] || st.channel,
        due: l.stall >= 4 ? `today · ${l.stall} days since contact` : l.stall > 0 ? 'today' : 'tomorrow',
        bucket: l.stall > 0 ? 1 : 2,
        ownerId: l.ownerId ?? null,
        companyId: l.companyId ?? null,
        dueIso: l.stall > 0 ? today : addDays(today, 1),
        note: '',
        done: false,
      };
    });
  // Hand-added tasks: open ones, plus those finished today (so ticking one doesn't make it vanish).
  const handTasks = s.leadTasks
    .filter((t) => !t.done || t.at === doneToday || (t.due && t.due >= today))
    .sort((a, b) => (a.due || today).localeCompare(b.due || today))
    .flatMap<TodayTask>((t) => {
      const lead = leadById(s, t.leadId);
      if (!lead) return [];
      const dueIso = t.due || today;
      return [
        {
          id: t.id,
          leadId: t.leadId,
          title: t.title,
          company: lead.company,
          stageName: stagesFor(s, lead.segment).find((x) => x.id === t.stageId)?.name ?? stageOf(s, lead).name,
          channelLabel: CHANNEL_LABELS[t.channel] || t.channel,
          due: dueIso === today ? 'today' : isoLabel(dueIso),
          // Ticked off today, an overdue task stays in Overdue (crossed out) until tomorrow.
          bucket: dueIso < today ? 0 : dueIso === today ? 1 : 2,
          ownerId: t.ownerId || null,
          companyId: lead.companyId ?? null,
          dueIso,
          note: t.note,
          done: t.done,
          task: { done: t.done, owner: memberName(s, t.ownerId, t.ownerName), dueIso, overdue: isOverdue(t, today) },
        },
      ];
    });
  const allTasks = [...handTasks, ...funnelTasks];
  const fields = taskFields(s, allTasks);
  const tasks = applyFilters(allTasks, fields, filters, { today, fiscalMonth: s.workspace.fiscalMonth });
  const noMatch = allTasks.length > 0 && tasks.length === 0;
  const groups = [
    { label: 'Overdue', fg: '#B42318', tasks: tasks.filter((t) => t.bucket === 0) },
    { label: 'Today', fg: '#0F1B16', tasks: tasks.filter((t) => t.bucket === 1) },
    { label: 'Next up', fg: '#475750', tasks: tasks.filter((t) => t.bucket === 2) },
  ];

  return (
    <Screen title="Today">
      <FilterBar
        row={<FilterRow fields={fields} value={filters} onChange={setFilters} people={filterPeople(s, me)} me={me} />}
        action={{ label: 'New task', onClick: () => set({ taskOpen: true }) }}
      />
      <div style={{ display: 'flex', flexDirection: 'column', gap: 20 }}>
        {s.leads.length === 0 && (
          <EmptyState title="Nothing to do yet" text="Today fills itself from your opportunities: each opportunity's next step in the funnel, plus the tasks you add. Start with an opportunity." action={{ label: 'New opportunity', onClick: () => set({ newLeadOpen: true }) }} />
        )}
        <div style={{ fontSize: 13.5, color: 'var(--text-2)', lineHeight: 1.55, maxWidth: 640 }}>Tasks are generated by the funnel, and each one opens with the script for that stage. Tasks added with New task sit alongside them until they are done.</div>
        <TeamTodayCard />
        <div data-group="Meetings today" data-testid="meetings-today" style={{ display: 'flex', flexDirection: 'column', gap: 10 }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: 9 }}>
            <span style={{ fontSize: 10.5, letterSpacing: '0.09em', textTransform: 'uppercase', color: 'var(--brand)' }}>Meetings today</span>
            <span style={{ flex: 1, height: 1, background: 'var(--border)' }} />
            <Link to={paths.calendar({ view: 'day', date: day })} style={{ fontSize: 11 }}>
              Calendar
            </Link>
            <span style={{ fontSize: 11, color: 'var(--text-2)' }}>{todays.length === 1 ? '1 meeting' : todays.length + ' meetings'}</span>
          </div>
          {todays.map((m) => (
            <Link key={m.id} to={paths.meeting(m.id)} data-meeting-id={m.id} className={blockClass(m, 'today-meeting')}>
              <span className="today-meeting-time">
                {instantToZoned(m.startsAt, tz).time}–{instantToZoned(m.endsAt, tz).time}
              </span>
              <span style={{ flex: 1, minWidth: 160, display: 'flex', flexDirection: 'column', gap: 3 }}>
                <span style={{ fontSize: 13.5, fontWeight: 600 }}>
                  <StatusMark m={m} /> {m.title}
                </span>
                <span style={{ fontSize: 12, color: 'var(--text-2)' }}>
                  {m.companyName}
                  {m.location ? ' · ' + m.location : ''}
                </span>
              </span>
              <TypeTag type={m.type} />
            </Link>
          ))}
        </div>
        {noMatch && <FilterEmpty noun="tasks" onClear={() => setFilters(clearAll(fields))} />}
        {!noMatch && groups.map((g) => (
          <div key={g.label} data-group={g.label} style={{ display: 'flex', flexDirection: 'column', gap: 10 }}>
            <div style={{ display: 'flex', alignItems: 'center', gap: 9 }}>
              <span style={{ fontSize: 10.5, letterSpacing: '0.09em', textTransform: 'uppercase', color: g.fg }}>{g.label}</span>
              <span style={{ flex: 1, height: 1, background: 'var(--border)' }} />
              <span style={{ fontSize: 11, color: 'var(--text-2)' }}>{g.tasks.length === 1 ? '1 task' : g.tasks.length + ' tasks'}</span>
            </div>
            {g.tasks.map((t) => (
              <div key={t.id} data-task={t.task ? t.id : undefined} style={{ background: 'var(--white)', border: '1px solid var(--border)', borderRadius: 10, padding: '14px 15px', display: 'flex', alignItems: 'center', gap: 14, flexWrap: 'wrap' }}>
                {t.task && (
                  <button
                    type="button"
                    title={t.task.done ? 'Reopen' : 'Mark done'}
                    onClick={() => toggleLeadTask(t.id)}
                    style={{ flex: '0 0 19px', width: 19, height: 19, borderRadius: 6, border: `1px solid ${t.task.done ? '#14503C' : '#CAD3CE'}`, background: t.task.done ? '#14503C' : '#FFFFFF', color: '#FFFFFF', fontSize: 11, cursor: 'pointer', display: 'flex', alignItems: 'center', justifyContent: 'center', padding: 0 }}
                  >
                    {t.task.done ? '✓' : ''}
                  </button>
                )}
                <div style={{ flex: 1, minWidth: 200, display: 'flex', flexDirection: 'column', gap: 3 }}>
                  <span style={{ fontSize: 13.5, fontWeight: 600, color: t.task?.done ? '#93A39B' : undefined, textDecoration: t.task?.done ? 'line-through' : 'none' }}>{t.title}</span>
                  <span style={{ fontSize: 12, color: t.task?.overdue ? 'var(--danger)' : 'var(--text-2)' }}>
                    {t.company} · {t.stageName} · {t.task?.overdue ? 'overdue · was due' : 'due'} {t.due}
                    {t.task ? ' · ' + t.task.owner : ''}
                  </span>
                </div>
                <span style={{ fontSize: 11.5, fontWeight: 500, background: 'var(--ink)', color: 'var(--white)', padding: '4px 9px', borderRadius: 6, whiteSpace: 'nowrap' }}>{t.channelLabel}</span>
                {t.task && (
                  <button type="button" className="btn-outline" title="Edit this task" onClick={() => set({ taskOpen: true, taskEditId: t.id })}>
                    Edit
                  </button>
                )}
                <button type="button" className="btn-outline" onClick={() => openLead(t.leadId)}>
                  {t.task ? 'Open opportunity' : 'Open script'}
                </button>
              </div>
            ))}
          </div>
        ))}
      </div>
    </Screen>
  );
}
